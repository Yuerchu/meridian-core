use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    generate_vendor_manifests(&manifest_dir, &out_dir);
    generate_model_families(&manifest_dir, &out_dir);
}

fn generate_vendor_manifests(manifest_dir: &Path, out_dir: &Path) {
    let vendors_dir = manifest_dir.join("src").join("vendors");
    println!("cargo:rerun-if-changed={}", vendors_dir.display());

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(read_dir) = fs::read_dir(&vendors_dir) {
        for entry in read_dir.flatten() {
            let path = entry.path();
            if !path.is_dir() {
                continue;
            }
            let manifest_path = path.join("manifest.json");
            if manifest_path.is_file() {
                let id = entry.file_name().to_string_lossy().into_owned();
                println!("cargo:rerun-if-changed={}", manifest_path.display());
                entries.push((id, manifest_path));
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let out_file = out_dir.join("vendor_manifests.rs");
    let mut code = String::from("// @generated by build.rs from src/vendors/*/manifest.json\n");
    code.push_str("pub const VENDOR_MANIFEST_SOURCES: &[(&str, &str)] = &[\n");
    for (id, path) in &entries {
        let abs = normalized_path(path);
        code.push_str(&format!("    ({id:?}, include_str!({abs:?})),\n"));
    }
    code.push_str("];\n");
    fs::write(&out_file, code).expect("write vendor_manifests.rs");
}

fn generate_model_families(manifest_dir: &Path, out_dir: &Path) {
    let models_dir = manifest_dir.join("src").join("models");
    println!("cargo:rerun-if-changed={}", models_dir.display());

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(read_dir) = fs::read_dir(&models_dir) {
        for entry in read_dir.flatten() {
            let path = entry.path();
            if path.is_file() && path.extension().and_then(|e| e.to_str()) == Some("json") {
                let stem = path
                    .file_stem()
                    .expect("json file stem")
                    .to_string_lossy()
                    .into_owned();
                println!("cargo:rerun-if-changed={}", path.display());
                entries.push((stem, path));
            }
        }
    }
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let out_file = out_dir.join("model_families.rs");
    let mut code = String::from("// @generated by build.rs from src/models/*.json\n");
    code.push_str("pub const MODEL_FAMILY_SOURCES: &[(&str, &str)] = &[\n");
    for (stem, path) in &entries {
        let abs = normalized_path(path);
        code.push_str(&format!("    ({stem:?}, include_str!({abs:?})),\n"));
    }
    code.push_str("];\n");
    fs::write(&out_file, code).expect("write model_families.rs");
}

fn normalized_path(path: &Path) -> String {
    path.to_string_lossy().replace('\\', "/")
}
